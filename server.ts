import { localApiOnly } from './local-api-guard.mjs';
import express from 'express';
import path from 'path';
import { createServer as createViteServer } from 'vite';
import { GoogleGenAI } from '@google/genai';

async function startServer() {
  const app = express();
app.use('/api', localApiOnly(() => PORT));
  const PORT = 3000;

  // Middleware to parse large JSON payloads (base64 images)
  app.use(express.json({ limit: '50mb' }));

  app.post('/api/generate-photo', async (req, res) => {
    try {
      const { image, scenePrompt } = req.body;
      
      if (!image || !scenePrompt) {
        return res.status(400).json({ error: 'Image and scenePrompt are required.' });
      }

      // Ensure the key exists
      if (!process.env.GEMINI_API_KEY) {
        return res.status(500).json({ error: 'GEMINI_API_KEY is not configured.' });
      }

      const ai = new GoogleGenAI({ 
        apiKey: process.env.GEMINI_API_KEY,
        httpOptions: {
          headers: {
            'User-Agent': 'aistudio-build',
          }
        }
      });

      // extract just the base64 part
      const matches = image.match(/^data:(.+);base64,(.+)$/);
      if (!matches) {
         return res.status(400).json({ error: 'Invalid image format.' });
      }
      const mimeType = matches[1];
      const base64Data = matches[2];

      const response = await ai.models.generateContent({
        model: 'gemini-3.1-flash-image',
        contents: {
          parts: [
            {
              inlineData: {
                data: base64Data,
                mimeType: mimeType,
              },
            },
            {
              text: `Put this person in a ${scenePrompt} historical scene, adapting lighting, clothing, and background to perfectly match the era. Produce a highly realistic photorealistic outcome while preserving the person's facial features and identity perfectly.`,
            },
          ],
        },
      });

      let resultImageBase64 = null;

      if (response.candidates && response.candidates.length > 0) {
        const parts = response.candidates[0].content.parts;
        if (parts) {
          for (const part of parts) {
            if (part.inlineData) {
              resultImageBase64 = `data:${part.inlineData.mimeType || 'image/png'};base64,${part.inlineData.data}`;
              break;
            }
          }
        }
      }

      if (!resultImageBase64) {
        return res.status(500).json({ error: 'No image was generated by the model.' });
      }

      res.json({ imageUrl: resultImageBase64 });
    } catch (error: any) {
      console.error('Error generating image:', error);
      res.status(500).json({ error: error.message || 'Failed to generate image' });
    }
  });

  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '127.0.0.1', () => {
    console.log(`Server running on http://localhost:${PORT}`);
  });
}

startServer();
